    /**
     * Что о жителе знают в округе — первое предложение биографии (роль: «Хозяин кабака в нижнем городе.»): так
     * собеседник узнаёт известного человека; пусто — не известен.
     */
    public static String reputation(String id) {
        String s = of(id);
        int dot = s.indexOf(". ");
        return dot < 0 ? s : s.substring(0, dot + 1);
    }

    /** Биография жителя по id (регистр не важен); пусто — нет в справочнике. */
    public static String of(String id) {
        if (id == null || id.isEmpty()) return "";
        String s = LORE.get(id.toUpperCase(Locale.ROOT));
        return s == null ? "" : s;
    }

    private static void put(String id, String text) {
        LORE.put(id.toUpperCase(Locale.ROOT), text);
    }

